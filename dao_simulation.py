import numpy as np
from scipy.integrate import odeint
import matplotlib.pyplot as plt

# 1. Thiết lập tham số kinh tế của DAO
B = 10.0   # Lợi ích chung khi DAO hoạt động tốt
c_v = 2.5  # Chi phí tự nghiên cứu & bỏ phiếu của Cử tri tích cực
c_d = 0.5  # Chi phí ủy quyền của Kẻ ăn không
R = 15.0   # Lợi ích trục lợi nếu Nhóm thông đồng chiếm đa số
L = 12.0   # Thiệt hại hệ thống khi bị tấn công

# 2. Định nghĩa hệ phương trình vi phân Replicator Dynamics
def replicator_dynamics(x, t):
    x1, x2, x3 = x  # x1: Active, x2: Free-rider, x3: Attacker

    # Nhóm thông đồng thắng nếu tự thân + 50% lượng phiếu ủy quyền vượt quá 50%
    attack_power = x3 + 0.5 * x2
    is_hijacked = 1.0 if attack_power > 0.5 else 0.0

    # Hàm lợi ích (Payoff) của từng nhóm
    f1 = B * (1 - is_hijacked) - L * is_hijacked - c_v
    f2 = B * (1 - is_hijacked) - L * is_hijacked - c_d
    f3 = R * is_hijacked - c_v

    # Lợi ích trung bình toàn quần thể
    f_avg = x1 * f1 + x2 * f2 + x3 * f3

    # Tốc độ thay đổi tỷ lệ từng nhóm theo thời gian
    dx1 = x1 * (f1 - f_avg)
    dx2 = x2 * (f2 - f_avg)
    dx3 = x3 * (f3 - f_avg)
    return [dx1, dx2, dx3]

# 3. Chạy mô phỏng
x0 = [0.6, 0.3, 0.1]  # Tỷ lệ ban đầu: 60% tích cực, 30% ủy quyền, 10% thông đồng
t = np.linspace(0, 20, 500)
sol = odeint(replicator_dynamics, x0, t)

# 4. Vẽ biểu đồ
plt.figure(figsize=(9, 5))
plt.plot(t, sol[:, 0], label='Cử tri tích cực (Active)', color='green', linewidth=2)
plt.plot(t, sol[:, 1], label='Kẻ ăn không ủy quyền (Free-rider)', color='blue', linewidth=2)
plt.plot(t, sol[:, 2], label='Nhóm thông đồng (Attacker)', color='red', linewidth=2)
plt.title('Mô phỏng tiến hóa tỷ lệ các nhóm chiến lược trong DAO')
plt.xlabel('Thời gian (t)')
plt.ylabel('Tỷ lệ quần thể')
plt.legend()
plt.grid(True, linestyle='--', alpha=0.6)
plt.show()

import networkx as nx
import random

# 1. Khởi tạo mạng lưới 100 thành viên DAO
N = 100
G = nx.DiGraph()
roles = ['Active']*50 + ['Free-rider']*40 + ['Attacker']*10
random.shuffle(roles)

for i in range(N):
    G.add_node(i, role=roles[i], base_tokens=random.uniform(10, 100))

total_tokens = sum(nx.get_node_attributes(G, 'base_tokens').values())
max_power_history = []

# 2. Chạy vòng lặp 1000 kỳ bỏ phiếu
for round_num in range(1000):
    G.clear_edges()
    delegates = [n for n, d in G.nodes(data=True) if d['role'] in ['Active', 'Attacker']]

    # Các Free-rider ủy quyền phiếu cho Active hoặc Attacker
    for n, d in G.nodes(data=True):
        if d['role'] == 'Free-rider':
            target = random.choice(delegates)
            G.add_edge(n, target)

    # Tính tổng quyền lực (Token bản thân + Token được ủy quyền)
    voting_power = {}
    for n in G.nodes():
        power = G.nodes[n]['base_tokens']
        for delegator in G.predecessors(n):
            power += G.nodes[delegator]['base_tokens']
        voting_power[n] = power

    # Ghi nhận tỷ lệ quyền lực của người nắm giữ lớn nhất ở vòng này
    max_power_history.append(max(voting_power.values()) / total_tokens)

# 3. Vẽ biểu đồ phân phối quyền lực qua 1000 vòng
plt.figure(figsize=(10, 4))
plt.plot(range(1000), max_power_history, color='purple', alpha=0.7, linewidth=1)
plt.axhline(y=sum(max_power_history)/1000, color='orange', linestyle='--', label='Mức tập trung trung bình')
plt.title('Biến động quyền lực tập trung cao nhất qua 1000 vòng bỏ phiếu')
plt.xlabel('Vòng bỏ phiếu')
plt.ylabel('Tỷ lệ quyền biểu quyết lớn nhất')
plt.legend()
plt.grid(True, alpha=0.4)
plt.show()

print(f"Tỷ lệ tập trung quyền lực cao nhất ghi nhận được: {max(max_power_history):.2%}")

# Vẽ trực quan mạng lưới ủy quyền ở vòng bỏ phiếu cuối cùng
plt.figure(figsize=(10, 8))

# Chia màu theo vai trò từng thành viên
color_map = []
for n, d in G.nodes(data=True):
    if d['role'] == 'Active':
        color_map.append('green')      # Cử tri tích cực: Xanh lá
    elif d['role'] == 'Free-rider':
        color_map.append('skyblue')    # Kẻ ăn không ủy quyền: Xanh dương
    else:
        color_map.append('red')        # Nhóm thông đồng: Đỏ

# Kích thước nút tỷ lệ thuận với tổng quyền lực biểu quyết
node_sizes = [voting_power[n] * 2 for n in G.nodes()]

# Sắp xếp bố cục đồ thị
pos = nx.spring_layout(G, k=0.35, seed=42)

nx.draw_networkx_nodes(G, pos, node_color=color_map, node_size=node_sizes, alpha=0.85)
nx.draw_networkx_edges(G, pos, edge_color='gray', arrows=True, alpha=0.4, arrowsize=10)

plt.title('Mạng lưới ủy quyền biểu quyết DAO (Xanh lá: Active | Xanh dương: Free-rider | Đỏ: Attacker)')
plt.axis('off')
plt.show()